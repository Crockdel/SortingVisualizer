        /// <summary>
        /// Получить научное объяснение алгоритма
        /// </summary>
        public static string GetAlgorithmExplanation(ISortingAlgorithm algorithm)
        {
            if (algorithm == null)
                return "Алгоритм не выбран";

            var sb = new StringBuilder();

            switch (algorithm.Name)
            {
                case string s when s.Contains("Пузырьковая"):
                    AppendBubbleSortExplanation(sb);
                    break;
                case string s when s.Contains("выбором"):
                    AppendSelectionSortExplanation(sb);
                    break;
                case string s when s.Contains("вставками"):
                    AppendInsertionSortExplanation(sb);
                    break;
                case string s when s.Contains("Быстрая"):
                    AppendQuickSortExplanation(sb);
                    break;
                case string s when s.Contains("слиянием"):
                    AppendMergeSortExplanation(sb);
                    break;
                case string s when s.Contains("Пирамидальная"):
                    AppendHeapSortExplanation(sb);
                    break;
                case string s when s.Contains("Bogo"):
                    AppendBogoSortExplanation(sb);
                    break;
                default:
                    sb.AppendLine("📊 АЛГОРИТМ: " + algorithm.Name);
                    sb.AppendLine();
                    sb.AppendLine("Подробное описание отсутствует.");
                    break;
            }

            return sb.ToString();
        }

