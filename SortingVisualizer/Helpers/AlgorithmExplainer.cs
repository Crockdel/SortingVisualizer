        private static void AppendBubbleSortExplanation(StringBuilder sb)
        {
            sb.AppendLine(@"
┌──────────────────────────────────────────────────────────────────────────────┐
│                       ПУЗЫРЬКОВАЯ СОРТИРОВКА (Bubble Sort)                   │
│                          Анализ и визуализация                               │
└──────────────────────────────────────────────────────────────────────────────┘

┌──────────────────────────────────────────────────────────────────────────────┐
│ I. ТЕОРЕТИЧЕСКОЕ ОПИСАНИЕ                                                    │
├──────────────────────────────────────────────────────────────────────────────┤
│                                                                              │
│  Пузырьковая сортировка — один из простейших алгоритмов сортировки.          │
│  Название отражает поведение элементов: большие элементы 'всплывают'         │
│  в конец массива подобно пузырькам воздуха в воде.                           │
│                                                                              │
│  ПРИНЦИП РАБОТЫ:                                                             │
│  1. Последовательно сравниваются пары соседних элементов                     │
│  2. Если элементы стоят в неправильном порядке (левый > правый) — обмен      │
│  3. За один проход наибольший элемент перемещается в конец                   │
│  4. Проходы повторяются, каждый раз уменьшая рабочую область                 │
│  5. Алгоритм завершается, когда за проход не было обменов                    │
│                                                                              │
└──────────────────────────────────────────────────────────────────────────────┘

┌──────────────────────────────────────────────────────────────────────────────┐
│ II. АСИМПТОТИЧЕСКАЯ СЛОЖНОСТЬ                                                │
├──────────────────────────────────────────────────────────────────────────────┤
│                                                                              │
│  📈 ВРЕМЕННАЯ СЛОЖНОСТЬ:                                                     │
│  • Худший случай (O(n²)): массив отсортирован в обратном порядке             │
│  • Средний случай (O(n²)): случайное расположение элементов                  │
│  • Лучший случай (O(n)): массив уже отсортирован (с оптимизацией)            │
│                                                                              │
│  💾 ПРОСТРАНСТВЕННАЯ СОЛЖНОСТЬ:                                              │
│  • O(1) — требуется только одна дополнительная переменная для обмена         │
│                                                                              │
│  🔢 ТОЧНОЕ КОЛИЧЕСТВО ОПЕРАЦИЙ (для n элементов):                            │
│  • Сравнений в худшем случае: n(n-1)/2                                       │
│  • Обменов в худшем случае: n(n-1)/2                                         │
│  • Сравнений в лучшем случае: n-1                                            │
│  • Обменов в лучшем случае: 0                                                │
│                                                                              │
